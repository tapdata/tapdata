package com.tapdata.tm.proxyprocess.service.auth;

import com.tapdata.tm.proxyprocess.constant.AgentCredentialConstants;
import lombok.extern.slf4j.Slf4j;
import org.apache.commons.lang3.StringUtils;
import org.bson.types.ObjectId;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.data.mongodb.core.MongoOperations;
import org.springframework.data.mongodb.core.query.Criteria;
import org.springframework.data.mongodb.core.query.Query;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.security.oauth2.core.AuthorizationGrantType;
import org.springframework.security.oauth2.core.ClientAuthenticationMethod;
import org.springframework.security.oauth2.server.authorization.client.RegisteredClient;
import org.springframework.security.oauth2.server.authorization.client.RegisteredClientRepository;
import org.springframework.security.oauth2.server.authorization.settings.ClientSettings;
import org.springframework.security.oauth2.server.authorization.settings.OAuth2TokenFormat;
import org.springframework.security.oauth2.server.authorization.settings.TokenSettings;
import org.springframework.stereotype.Service;

import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * Publishes the OAuth2 client an agent generated for itself.
 *
 * <p>Why the agent generates the secret instead of TM: TM is the
 * <em>registry</em>, not the issuer. If TM could mint credentials for any agent,
 * anyone with console access could obtain access to that agent without touching
 * it. Letting the agent generate them keeps the credential owned by the resource
 * it protects; TM only records what it was told.
 *
 * <p>Deliberately isolated from {@code ApplicationService}: those rows are the
 * general-purpose OAuth2 clients a user creates in the console. Agent clients are
 * machine clients that must never appear in, or be editable through, that surface.
 */
@Service
@Slf4j
public class AgentOAuth2ClientRegistrar {

    private static final String COLLECTION = AgentCredentialConstants.OAUTH2_CLIENT_COLLECTION;
    private static final String ROLE_COLLECTION = "Role";

    private final RegisteredClientRepository registeredClientRepository;
    private final MongoOperations mongoOperations;
    private final PasswordEncoder passwordEncoder;

    @Autowired
    public AgentOAuth2ClientRegistrar(RegisteredClientRepository registeredClientRepository,
                                       MongoOperations mongoOperations,
                                       PasswordEncoder passwordEncoder) {
        this.registeredClientRepository = registeredClientRepository;
        this.mongoOperations = mongoOperations;
        this.passwordEncoder = passwordEncoder;
    }

    /**
     * Create or update the OAuth2 client for an agent.
     *
     * <p>Idempotent: re-registering with the same secret keeps the row stable, so
     * an agent restart does not invalidate tokens already handed to callers.
     *
     * @param clientId 24-hex client id the agent derived for itself
     * @param secret   plaintext secret as generated by the agent
     * @param scopeIds role ids to grant; empty is allowed and grants only {@code $everyone}
     */
    public void register(String clientId, String secret, List<ObjectId> scopeIds) {
        if (!AgentCredentialPolicy.isObjectIdHex(clientId)) {
            throw new IllegalArgumentException("Agent client id must be a 24 character hex string");
        }
        if (!AgentCredentialPolicy.isValidSecret(secret)) {
            throw new IllegalArgumentException("Agent client secret is invalid");
        }
        List<ObjectId> scopes = scopeIds == null ? Collections.emptyList() : scopeIds;

        TokenSettings tokenSettings = TokenSettings.builder()
                .accessTokenTimeToLive(AgentCredentialConstants.ACCESS_TOKEN_TTL)
                .accessTokenFormat(OAuth2TokenFormat.SELF_CONTAINED)
                .reuseRefreshTokens(true)
                .refreshTokenTimeToLive(AgentCredentialConstants.ACCESS_TOKEN_TTL)
                .build();

        RegisteredClient.Builder builder = RegisteredClient.withId(clientId)
                .clientId(clientId)
                .clientName(AgentCredentialConstants.CLIENT_NAME_PREFIX + clientId)
                .clientAuthenticationMethod(ClientAuthenticationMethod.CLIENT_SECRET_BASIC)
                .clientAuthenticationMethod(ClientAuthenticationMethod.CLIENT_SECRET_POST)
                .authorizationGrantType(AuthorizationGrantType.CLIENT_CREDENTIALS)
                .clientSettings(ClientSettings.builder().requireAuthorizationConsent(false).build())
                .tokenSettings(tokenSettings)
                /*
                 * Encoded with the authorization server's own encoder instead of assuming a
                 * format. That encoder is currently NoOpPasswordEncoder, kept unchanged so the
                 * console clients keep authenticating; going through it means this code keeps
                 * working if that ever changes.
                 */
                .clientSecret(passwordEncoder.encode(secret));

        for (ObjectId scope : scopes) {
            if (scope != null) {
                builder.scope(scope.toHexString());
            }
        }
        registeredClientRepository.save(builder.build());
        log.info("Registered agent OAuth2 client {} with {} scope(s)", clientId, scopes.size());
    }

    /** Remove the agent's client so a deleted agent cannot keep minting access tokens. */
    public void unregister(String clientId) {
        if (StringUtils.isBlank(clientId)) {
            return;
        }
        mongoOperations.remove(Query.query(Criteria.where("clientId").is(clientId)), COLLECTION);
        log.info("Unregistered agent OAuth2 client {}", clientId);
    }

    /**
     * Resolve a role name to its id.
     *
     * <p>{@code RegisteredClient.scopes} holds role <em>ids</em>, not names:
     * {@code AuthorizationConfig#jwtCustomizer} maps each scope back through {@code RoleEntity}
     * to build the JWT {@code roles} claim. Passing a name here yields a token that carries only
     * {@code $everyone}, which the agent would reject.
     */
    public Optional<ObjectId> findRoleId(String roleName) {
        if (StringUtils.isBlank(roleName)) {
            return Optional.empty();
        }
        Map<?, ?> role = mongoOperations.findOne(
                Query.query(Criteria.where("name").is(roleName)), Map.class, ROLE_COLLECTION);
        if (role == null || role.get("_id") == null) {
            return Optional.empty();
        }
        Object id = role.get("_id");
        return id instanceof ObjectId objectId ? Optional.of(objectId) : Optional.empty();
    }

    /** True when this client id already belongs to an agent. */
    public boolean exists(String clientId) {
        if (StringUtils.isBlank(clientId)) {
            return false;
        }
        return mongoOperations.exists(
                Query.query(Criteria.where("clientId").is(clientId)), COLLECTION);
    }
}
